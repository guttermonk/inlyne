#!/bin/bash

# Test script for verifying search keybind functionality in Inlyne
# This script provides instructions for manual testing of the search feature

echo "================================================"
echo "Inlyne Search Keybind Test Script"
echo "================================================"
echo ""
echo "This script will help you test that non-search keybinds are properly"
echo "disabled while search mode is active."
echo ""
echo "Building Inlyne..."
cargo build --release 2>/dev/null || cargo build

echo ""
echo "Starting Inlyne with test document..."
echo ""
echo "TEST INSTRUCTIONS:"
echo "=================="
echo ""
echo "1. ACTIVATING SEARCH:"
echo "   - Press Ctrl+F (or Cmd+F on Mac) to activate search mode"
echo "   - The window title should show '[SEARCH MODE] Type to search...'"
echo ""
echo "2. TEST THAT OTHER KEYBINDS ARE DISABLED:"
echo "   While in search mode, try these keys (they should NOT work):"
echo "   - j/k or Arrow keys (should NOT scroll)"
echo "   - Space/Shift+Space (should NOT page down/up)"
echo "   - Page Up/Page Down (should NOT navigate pages)"
echo "   - Home/End (should NOT jump to top/bottom)"
echo "   - Ctrl+Plus/Minus (should NOT zoom)"
echo "   - Alt+Left/Right (should NOT navigate history)"
echo "   - g/G (should NOT jump to top/bottom)"
echo "   - Instead, these keys should either:"
echo "     * Be typed into the search query (for regular letters)"
echo "     * Be ignored completely (for special navigation keys)"
echo ""
echo "3. TYPE A SEARCH QUERY:"
echo "   - Type 'test' (without quotes)"
echo "   - The window title should update to show '[SEARCH] test (1/X)'"
echo "   - The first match should be highlighted"
echo ""
echo "4. TEST SEARCH NAVIGATION (these SHOULD work):"
echo "   - Press Enter: Activates navigation mode and goes to next match"
echo "   - Press 'n': After pressing Enter, moves to next match"
echo "   - Press Shift+n: After pressing Enter, moves to previous match"
echo "   - Press Tab: Moves to next match"
echo "   - Press Shift+Tab: Moves to previous match"
echo ""
echo "5. TEST THAT YOU CAN STILL TYPE:"
echo "   - Before pressing Enter, you should be able to type 'n' in your search"
echo "   - Try searching for 'section' or 'content'"
echo "   - The letter 'n' should appear in your search query"
echo ""
echo "6. TEST SEARCH CANCELLATION:"
echo "   - Press Escape to exit search mode"
echo "   - The window title should return to normal"
echo "   - All regular keybinds should work again"
echo ""
echo "7. VERIFY NORMAL MODE:"
echo "   After canceling search, verify these keys work normally:"
echo "   - j/k or Arrow keys (should scroll)"
echo "   - Space (should page down)"
echo "   - Other navigation keys should function"
echo ""
echo "8. TEST COPY DURING SEARCH:"
echo "   - Activate search again (Ctrl+F)"
echo "   - Select some text with the mouse"
echo "   - Press Ctrl+C (or Cmd+C) to copy"
echo "   - This should still work during search"
echo ""
echo "Press Enter to launch Inlyne with the test document..."
read -r

# Launch Inlyne with the test document
./target/release/inlyne test_search_keybinds/test.md 2>/dev/null || \
./target/debug/inlyne test_search_keybinds/test.md 2>/dev/null || \
cargo run -- test_search_keybinds/test.md

echo ""
echo "Test completed. If all behaviors matched the expected results above,"
echo "then the search keybind isolation is working correctly!"
echo ""